from hex_conversion import to_hex
from writer import Writer


def make_metadata_header(
    procedure, is_inline, module_name, exported_procedures
):
    mangling = exported_procedures.get(procedure.address)
    hex_addr = to_hex(procedure.address)
    lines = [
        "/*",
        *_make_comment_lines(procedure),
        "* Module:                 {}".format(module_name),
        "* Entry point:            0x{}".format(hex_addr),
    ]
    if mangling is not None and mangling.startswith("?"):
        lines.append("* VC++ mangling:          {}".format(mangling))
    lines.append("*/")
    writer = Writer()
    if is_inline:
        with writer.indent():
            _write_lines(writer, lines)
    else:
        _write_lines(writer, lines)
    return writer.get_string()


def _write_lines(writer, lines):
    for line in lines:
        writer.write_line(line)


def _make_comment_lines(procedure):
    if procedure.proc_decl.is_default_constructor_closure:
        return [
            "*",
            "* Implicit definition of default constructor closure.",
            "* Generated by compiler.",
            "*",
        ]
    return []

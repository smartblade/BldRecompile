"""Print map of code blocks of a module compiled with Visual C++.

The linker aligns code of each object file and each COMDAT section (inline
functions emitted out of line, template instances, procedures generated by
compiler) at 16 bytes and fills gaps with 'int 3' (0xCC). Procedures of one
.cpp file compiled without /Gy follow each other without gaps in order of
their definitions. So code between gaps is either a .cpp file or a single
COMDAT procedure.

Procedures are found from 'PROC' labels of assembler files (code.str or
native.asm), call targets and exports in raw.txt and 'Entry point' comments
of sources.
"""
import argparse
import collections
import os
import re
import sys

raw_line_regexp = re.compile(r'^(?P<addr>[0-9A-F]{8}): (?P<bytes>[0-9A-F]+)\s')
export_regexp = re.compile(r'^\* Export: (?P<name>[^,]+),')
section_regexp = re.compile(r'^Section (?P<name>\S+)')
proc_regexp = re.compile(r'^l(?P<addr>[0-9A-F]{8}) PROC', re.M)
src_proc_regexp = re.compile(
    r'Module:\s+(?P<module>\S+)\s*\n'
    r'\* Entry point:\s+0x(?P<addr>[0-9A-F]{8})\s*\n'
    r'(?:\* VC\+\+ mangling:\s+(?P<mangling>\S+)\s*\n)?'
    r'\*/\s*\n'
    r'(?:\s*//[^\n]*\n|\s*\n)*'
    r'(?P<native>#ifndef BLD_NATIVE\s*\n)?'
    r'(?P<decl>[^\n{]*)')

ALIGNMENT = 16


class Procedure:
    def __init__(self, addr):
        self.addr = addr
        self.export = None
        self.file_name = None
        self.declaration = None
        self.is_implemented = False

    @property
    def name(self):
        return self.declaration or self.export or ""


def read_raw(file_name):
    """Read instructions of .text section, call targets and exports."""
    instructions = []
    call_targets = set()
    exports = {}
    export = None
    is_call = False
    is_text = False
    with open(file_name, encoding="cp1251", errors="replace") as f:
        for line in f:
            match = section_regexp.match(line)
            if match:
                is_text = match.group("name") == ".text"
                continue
            if not is_text:
                continue
            if line.startswith("* Call:"):
                is_call = True
                continue
            match = export_regexp.match(line)
            if match:
                export = match.group("name")
                continue
            match = raw_line_regexp.match(line)
            if not match:
                continue
            addr = int(match.group("addr"), 16)
            instructions.append((addr, match.group("bytes")))
            if is_call:
                call_targets.add(addr)
                is_call = False
            if export is not None:
                exports[addr] = export
                export = None
    return instructions, call_targets, exports


def read_asm_procedures(file_names):
    procedures = set()
    for file_name in file_names:
        with open(file_name, encoding="cp1251", errors="replace") as f:
            procedures.update(
                int(addr, 16) for addr in proc_regexp.findall(f.read()))
    return procedures


def read_src_procedures(src_dir, module):
    procedures = {}
    for root, dirs, files in os.walk(src_dir):
        dirs.sort()
        for file in sorted(files):
            if not file.lower().endswith((".cpp", ".h")):
                continue
            path = os.path.join(root, file)
            with open(path, encoding="cp1251", errors="replace") as f:
                text = f.read().replace("\r", "")
            for match in src_proc_regexp.finditer(text):
                if match.group("module") != module:
                    continue
                addr = int(match.group("addr"), 16)
                procedures[addr] = (
                    os.path.relpath(path, src_dir).replace("\\", "/"),
                    match.group("decl").strip(),
                    match.group("native") is None,
                )
    return procedures


def make_blocks(instructions):
    """Split instructions to blocks separated by aligning 'int 3'."""
    blocks = []
    start = None
    end = None
    i = 0
    while i < len(instructions):
        addr, hex_bytes = instructions[i]
        if hex_bytes == "CC":
            j = i
            while j < len(instructions) and instructions[j][1] == "CC":
                j += 1
            next_addr = instructions[j][0] if j < len(instructions) else None
            if next_addr is None or next_addr % ALIGNMENT == 0:
                if start is not None:
                    blocks.append((start, end))
                start = None
                i = j
                continue
        if start is None:
            start = addr
        end = addr + len(hex_bytes) // 2
        i += 1
    if start is not None:
        blocks.append((start, end))
    return blocks


def print_map(blocks, procedures, out):
    file_blocks = collections.defaultdict(list)
    single_blocks = collections.defaultdict(list)
    for index, (start, end) in enumerate(blocks, 1):
        block_procs = [
            procedures[addr] for addr in sorted(procedures)
            if start <= addr < end
        ]
        files = sorted(set(
            proc.file_name for proc in block_procs if proc.file_name))
        if len(block_procs) == 1:
            kind = "single procedure"
        else:
            kind = "{} procedures".format(len(block_procs))
        out.write("Block {} {:08X}-{:08X} {} bytes, {}\n".format(
            index, start, end, end - start, kind))
        if len(files) > 1:
            out.write("    note: procedures of several files: {}\n".format(
                ", ".join(files)))
        for proc in block_procs:
            out.write("    {:08X} {:<28} {}{}\n".format(
                proc.addr,
                proc.file_name or "-",
                proc.name,
                "" if proc.is_implemented or not proc.file_name
                else " (BLD_NATIVE)",
            ))
            if proc.file_name:
                if index not in file_blocks[proc.file_name]:
                    file_blocks[proc.file_name].append(index)
                if len(block_procs) == 1:
                    single_blocks[proc.file_name].append(index)
    out.write("\nFiles:\n")
    for file_name in sorted(file_blocks):
        indices = file_blocks[file_name]
        out.write("    {:<28} blocks {}".format(
            file_name, ", ".join(str(i) for i in indices)))
        single = single_blocks[file_name]
        if file_name.lower().endswith(".cpp") and single and len(indices) > 1:
            out.write(
                " (single procedure blocks {}: inline or template?)".format(
                    ", ".join(str(i) for i in single)))
        out.write("\n")


def main():
    arg_parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    arg_parser.add_argument("raw", help="raw.txt of the module")
    arg_parser.add_argument(
        "--asm", action="append", default=[],
        help="assembler file with 'PROC' labels (code.str or native.asm)")
    arg_parser.add_argument("--src", help="sources with 'Entry point' comments")
    arg_parser.add_argument(
        "--module",
        help="module name in sources (default: module.txt next to raw.txt)")
    args = arg_parser.parse_args()

    instructions, call_targets, exports = read_raw(args.raw)
    addresses = set(call_targets) | set(exports)
    addresses |= read_asm_procedures(args.asm)
    src_procedures = {}
    if args.src:
        module = args.module
        if module is None:
            module_file = os.path.join(os.path.dirname(args.raw), "module.txt")
            with open(module_file) as f:
                module = f.readline().strip()
        src_procedures = read_src_procedures(args.src, module)
        addresses |= set(src_procedures)
    procedures = {}
    for addr in addresses:
        proc = Procedure(addr)
        proc.export = exports.get(addr)
        if addr in src_procedures:
            proc.file_name, proc.declaration, proc.is_implemented = (
                src_procedures[addr])
        procedures[addr] = proc
    print_map(make_blocks(instructions), procedures, sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
